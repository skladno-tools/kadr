// @ts-check
// Builds the bundled font library in /fonts from the pinned Fontsource
// packages listed in ./package.json.
//
//   cd tools/fonts && npm ci && node build.mjs
//
// Output:
//   fonts/<id>/*.woff2    font files, split by script (Latin, Cyrillic, ...)
//   fonts/<id>/LICENSE    the font's license
//   fonts/fonts.css       @font-face rules for every family
//   fonts/catalog.json    machine-readable list of families
//   fonts/README.md       license notice and list of families
// It also updates the font enum in schema/0.1/kadr.schema.json so the schema
// always matches the bundled library.
//
// The library is built in fonts.building/ and replaces fonts/ only when the
// whole build has succeeded, so a failed build leaves fonts/ as it was.
//
// Every license must carry a copyright notice. When the license in a package
// has none (two Adobe families in Fontsource carry only "Google Inc."), the
// notice written in the font files themselves is put in its place.

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, rmSync, existsSync, renameSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { nameOf } from './woff2.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const modules = join(here, 'node_modules');
const target = join(root, 'fonts');
const out = join(root, 'fonts.building');
const old = join(root, 'fonts.old');
const schemaPath = join(root, 'schema', '0.1', 'kadr.schema.json');

// Our own grouping. It describes how a family is meant to be used on slides,
// which is not always the same as the upstream category.
const library = [
  // Sans: body text and headings
  ['inter', 'sans'], ['manrope', 'sans'], ['onest', 'sans'], ['golos-text', 'sans'],
  ['geologica', 'sans'], ['commissioner', 'sans'], ['rubik', 'sans'], ['nunito', 'sans'],
  ['mulish', 'sans'], ['open-sans', 'sans'], ['noto-sans', 'sans'], ['ibm-plex-sans', 'sans'],
  ['montserrat', 'sans'], ['raleway', 'sans'], ['jost', 'sans'], ['exo-2', 'sans'],
  ['wix-madefor-text', 'sans'], ['wix-madefor-display', 'sans'], ['pt-sans', 'sans'],
  // Serif
  ['literata', 'serif'], ['source-serif-4', 'serif'], ['lora', 'serif'], ['merriweather', 'serif'],
  ['noto-serif', 'serif'], ['eb-garamond', 'serif'], ['cormorant', 'serif'], ['alegreya', 'serif'],
  ['playfair-display', 'serif'], ['pt-serif', 'serif'],
  // Display: large headings and numbers only
  ['unbounded', 'display'], ['oswald', 'display'], ['comfortaa', 'display'], ['tektur', 'display'],
  ['russo-one', 'display'], ['yeseva-one', 'display'], ['press-start-2p', 'display'],
  // Handwriting
  ['caveat', 'handwriting'], ['lobster', 'handwriting'], ['pacifico', 'handwriting'],
  // Monospace: code
  ['jetbrains-mono', 'mono'], ['fira-code', 'mono'], ['source-code-pro', 'mono'],
  ['roboto-mono', 'mono'], ['ibm-plex-mono', 'mono'],
];

/** @param {string} id */
const pkgDir = (id) => {
  for (const scope of ['@fontsource-variable', '@fontsource']) {
    const dir = join(modules, scope, id);
    if (existsSync(dir)) return { dir, scope };
  }
  throw new Error(`package for "${id}" is not installed; run npm ci`);
};

// Pulls the @font-face blocks out of a Fontsource stylesheet.
/** @param {string} cssPath */
const faces = (cssPath) => {
  const css = readFileSync(cssPath, 'utf8');
  return [...css.matchAll(/@font-face\s*{([^}]*)}/g)].map(([, body]) => {
    /** @param {string} k */
    const get = (k) => body.match(new RegExp(`${k}:\\s*([^;]+);`))?.[1].trim();
    const file = get('src')?.match(/url\(\.\/files\/([^)]+)\)/)?.[1];
    if (!file) throw new Error(`${cssPath}: a @font-face without a file`);
    return {
      style: get('font-style'),
      weight: get('font-weight'),
      file,
      range: get('unicode-range'),
    };
  });
};

// A run that stopped in the middle of the swap below leaves the library in
// fonts.old/ and no fonts/: put it back before anything else.
if (!existsSync(target) && existsSync(old)) {
  renameSync(old, target);
  console.log('fonts/ was restored from fonts.old/, left by an interrupted build');
}
rmSync(out, { recursive: true, force: true });
rmSync(old, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const hasNotice = (/** @type {string} */ text) => /copyright|\u00a9|\(c\)/i.test(text);

const catalog = [];
const css = ['/* Generated by tools/fonts/build.mjs. Do not edit by hand. */\n'];

for (const [id, category] of library) {
  const { dir, scope } = pkgDir(id);
  const meta = JSON.parse(readFileSync(join(dir, 'metadata.json'), 'utf8'));
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  if (meta.license.type !== 'OFL-1.1') throw new Error(`${id}: unexpected license ${meta.license.type}`);
  if (!meta.subsets.includes('cyrillic')) throw new Error(`${id}: no Cyrillic`);

  const variable = scope === '@fontsource-variable';
  /** @type {string[]} */
  const sheets = variable
    ? ['wght.css', 'wght-italic.css']
    : meta.weights.flatMap((/** @type {number} */ w) => [`${w}.css`, `${w}-italic.css`]);

  const list = sheets.filter((s) => existsSync(join(dir, s))).flatMap((s) => faces(join(dir, s)));
  mkdirSync(join(out, id), { recursive: true });

  // The copyright notice in the font files is the authoritative one.
  const notices = [...new Set(list.map((f) => nameOf(readFileSync(join(dir, 'files', f.file)), 0)))];
  if (notices.some((n) => n === undefined || !hasNotice(n))) throw new Error(`${id}: a font file without a copyright notice`);
  let license = readFileSync(join(dir, 'LICENSE'), 'utf8');
  const body = license.indexOf('This Font Software is licensed under the SIL Open Font License, Version 1.1.');
  if (body < 0) throw new Error(`${id}: the license is not the usual OFL text`);
  let copyright = meta.license.attribution.split(/\s+\S+\.ttf:/)[0].trim();
  if (!hasNotice(license.slice(0, body))) {
    license = `${notices.join('\n')}\n\n${license.slice(body)}`;
    copyright = notices.join(' ');
    console.log(`${id}: the package's license has no copyright notice; using the one in the font files`);
  } else if (!hasNotice(copyright)) {
    throw new Error(`${id}: the package's metadata has no copyright notice`);
  }
  writeFileSync(join(out, id, 'LICENSE'), license);

  for (const f of list) {
    copyFileSync(join(dir, 'files', f.file), join(out, id, f.file));
    css.push(`@font-face {
  font-family: '${meta.family}';
  font-style: ${f.style};
  font-weight: ${f.weight};
  font-display: swap;
  src: url(./${id}/${f.file}) format('woff2');
  unicode-range: ${f.range};
}
`);
  }

  const wght = meta.variable?.wght;
  catalog.push({
    id,
    family: meta.family,
    category,
    variable,
    weights: variable ? [Number(wght.min), Number(wght.max)] : meta.weights,
    italic: list.some((f) => f.style === 'italic'),
    subsets: meta.subsets,
    license: meta.license.type,
    copyright,
    source: `${pkg.name}@${pkg.version}`,
  });
}

writeFileSync(join(out, 'fonts.css'), css.join('\n'));
writeFileSync(join(out, 'catalog.json'), JSON.stringify({ fonts: catalog }, null, 2) + '\n');

const readme = [
  '# Bundled fonts',
  '',
  'Generated by `tools/fonts/build.mjs`. Do not edit by hand.',
  '',
  'These fonts are not covered by the Apache License of the rest of the repository.',
  'Each family is distributed under the SIL Open Font License 1.1; its full license',
  'and copyright notice are in the `LICENSE` file in its folder.',
  '',
  '| Family | Category | Copyright | Source |',
  '|---|---|---|---|',
  ...catalog.map((f) => `| ${f.family} | ${f.category} | ${f.copyright.replace(/\|/g, '\\|')} | \`${f.source}\` |`),
  '',
];
writeFileSync(join(out, 'README.md'), readme.join('\n'));

// The schema's list of allowed families follows the library. It is written
// beside the schema first and moved into place together with the library.
const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
schema.$defs.fontFamily.enum = catalog.map((f) => f.family);
const schemaNext = `${schemaPath}.building`;
writeFileSync(schemaNext, JSON.stringify(schema, null, 2) + '\n');

// Everything is built: replace the library and the schema.
if (existsSync(target)) renameSync(target, old);
renameSync(out, target);
renameSync(schemaNext, schemaPath);
rmSync(old, { recursive: true, force: true });

console.log(`${catalog.length} families written to fonts/`);
